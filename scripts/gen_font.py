#!/usr/bin/env python3
"""Convert printable ASCII from a PSF console font into kernel/drivers/font8x16.c."""
import gzip, struct, sys

src = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/consolefonts/Lat15-VGA16.psf.gz"
data = gzip.open(src).read()
if data[:2] == b"\x36\x04":
    mode, h = data[2], data[3]
    n = 512 if mode & 1 else 256
    w, off, size = 8, 4, h
    glyphs = [data[off + i * size: off + (i + 1) * size] for i in range(n)]
    table = data[off + n * size:]
    umap = {}
    if mode & 2:
        i = g = 0
        while g < n and i + 1 < len(table):
            u = struct.unpack_from("<H", table, i)[0]; i += 2
            if u == 0xFFFF:
                g += 1
            elif u != 0xFFFE:
                umap.setdefault(u, g)
else:
    _, ver, off, flags, n, size, h, w = struct.unpack_from("<8I", data, 0)
    glyphs = [data[off + i * size: off + (i + 1) * size] for i in range(n)]
    table = data[off + n * size:]
    umap = {}
    if flags & 1:
        g, i = 0, 0
        while g < n and i < len(table):
            b = table[i]
            if b == 0xFF:
                g += 1; i += 1; continue
            if b == 0xFE:
                i += 1; continue
            l = 1 if b < 0x80 else 2 if b < 0xE0 else 3 if b < 0xF0 else 4
            umap.setdefault(ord(table[i:i + l].decode("utf-8", "replace")[0]), g)
            i += l
assert w == 8 and h == 16, (w, h)
out = ["/* Generated by scripts/gen_font.py from %s (public domain console font). */" % src.split("/")[-1],
       "#include <sobi/types.h>", "",
       "const uint8_t font8x16[95][16] = {"]
for c in range(0x20, 0x7F):
    g = glyphs[umap.get(c, c)]
    out.append("    { " + ", ".join("0x%02X" % b for b in g) + " }, /* %r */" % chr(c))
out.append("};")
open("kernel/drivers/font8x16.c", "w").write("\n".join(out) + "\n")
